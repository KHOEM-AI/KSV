// KSV — International System (Domain #1, part 2: Language)
// File: src/i18n/translations.ts
//
// Principle (project spec, section 13):
//   "The system should separate language content from application logic.
//    Additional languages can be added without redesigning the app."
//
// HOW THIS WORKS:
//   Every piece of UI text in the whole app is a KEY (e.g. "nav.dashboard"),
//   never a hardcoded string. Each language is one flat object mapping
//   every key to that language's text. To add a new language, add one
//   new entry to LANGUAGES + one new object here — no component changes.
// ======================================================================

