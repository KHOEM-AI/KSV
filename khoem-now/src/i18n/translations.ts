/** Fallback chain: missing key in a language falls back to English,
 *  never to a blank string — this is what "no redesign needed" means
 *  when a language's dictionary is still incomplete. */
export function translate(lang: LanguageCode, key: string, vars?: Record<string, string | number>): string {
  const raw = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), raw);
}
